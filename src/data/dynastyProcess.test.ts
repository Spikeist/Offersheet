import { describe, expect, it } from "vitest";
import { STALE_PUBLIC_RETAIN_MS, TTL } from "@/server/cache";
import { DYNASTYPROCESS_CACHE_KEY, DYNASTYPROCESS_COLUMNS, DYNASTYPROCESS_IDS_URL, DYNASTYPROCESS_MIN_ROWS, DYNASTYPROCESS_REDUCER, DYNASTYPROCESS_TIMEOUT_MS, fetchDynastyProcessIds, parseDynastyProcessCsv } from "./dynastyProcess";
import { fakeHttp, fixtureDynastyCsv, fixtureDynastyRows, padDynastyCsv } from "./testSupport";

const HEADER = "mfl_id,sportradar_id,gsis_id,sleeper_id,espn_id,yahoo_id,fleaflicker_id,name,position,team,birthdate";

describe("DynastyProcess db_playerids.csv", () => {
  // The shared fixtures are regenerated by `npm run probe:shared`, so these tests check invariants, not counts.
  it("parses the committed subset: every row has a Sleeper id and no 'NA' survives", () => {
    const rows = fixtureDynastyRows();
    expect(rows.length).toBeGreaterThan(1000);
    expect(rows.every((r) => r.sleeperId !== null)).toBe(true);
    const idValues = rows.flatMap((r) => [r.sleeperId, r.espnId, r.yahooId, r.mflId, r.fleaflickerId, r.sportradarId, r.gsisId]);
    expect(idValues.includes("NA")).toBe(false);
    expect(rows.filter((r) => r.espnId).length / rows.length).toBeGreaterThan(0.9);
    expect(rows.every((r) => r.mflId !== null)).toBe(true); // mfl_id is complete in DynastyProcess
    // MFL-style team codes are kept as written; the crosswalk derives their Sleeper codes.
    expect(new Set(rows.map((r) => r.team))).toContain("JAC");
    expect(new Set(rows.map((r) => r.position))).toContain("PK");
  });

  it("maps NA to null, keeps MFL leading zeros and cleans free-agent teams", () => {
    const csv = `${HEADER}\n0501,NA,NA,NA,NA,NA,NA,Team Defense,DEF,DAL,NA\n17001,0a1b2c3d-0000-4000-8000-00000000aaaa,00-0090001,90001,4400001,33001,NA,Zorblax Quintavious,QB,FA*,1999-01-01\n`;
    const [def, qb] = parseDynastyProcessCsv(csv);
    expect(def).toEqual({ sleeperId: null, espnId: null, yahooId: null, mflId: "0501", fleaflickerId: null, sportradarId: null, gsisId: null, name: "Team Defense", position: "DEF", team: "DAL" });
    expect(qb).toMatchObject({ sleeperId: "90001", espnId: "4400001", yahooId: "33001", mflId: "17001", gsisId: "00-0090001", team: null });
  });

  it("names a missing column in a BAD_RESPONSE error", () => {
    const csv = `${HEADER.replace("espn_id,", "")}\n1,NA,NA,1,NA,NA,A,QB,DAL,NA\n`;
    expect(() => parseDynastyProcessCsv(csv)).toThrow(expect.objectContaining({ code: "BAD_RESPONSE", detail: { path: "header.espn_id" } }));
    expect(DYNASTYPROCESS_COLUMNS).toContain("espn_id");
  });

  it("reports unparseable CSV and empty files as BAD_RESPONSE", () => {
    expect(() => parseDynastyProcessCsv(`${HEADER}\n1,"unterminated,NA\n`)).toThrow(expect.objectContaining({ code: "BAD_RESPONSE" }));
    expect(() => parseDynastyProcessCsv(`${HEADER}\n`)).toThrow(expect.objectContaining({ code: "BAD_RESPONSE", detail: { path: "(root)" } }));
  });

  it("fetches through the HttpClient: 24 h cache, 7-day saved copy, one retry", async () => {
    const csv = padDynastyCsv(fixtureDynastyCsv());
    const { http, calls } = fakeHttp({ [DYNASTYPROCESS_IDS_URL]: { text: csv, fromCache: true } });
    const res = await fetchDynastyProcessIds(http);
    expect(res.rows).toHaveLength(fixtureDynastyRows().length + DYNASTYPROCESS_MIN_ROWS);
    expect(res).toMatchObject({ fromCache: true, stale: false });
    // Reduced at fetch time under a key of its own (src/data/reduce.ts), league-independent (public: the shared cache's lock).
    expect(calls[0]?.opts?.cache).toEqual({ key: `dynastyprocess:${DYNASTYPROCESS_IDS_URL}#${DYNASTYPROCESS_REDUCER.id}`, ttlMs: TTL.idMap, retainMs: STALE_PUBLIC_RETAIN_MS, staleIfError: true, public: true });
    expect(calls[0]?.opts?.cache?.key).toBe(DYNASTYPROCESS_CACHE_KEY);
    expect(calls[0]?.opts?.transformText).toBe(DYNASTYPROCESS_REDUCER.reduce);
    expect(calls[0]?.opts).toMatchObject({ maxRetries: 1, timeoutMs: DYNASTYPROCESS_TIMEOUT_MS });
    await expect(fetchDynastyProcessIds(fakeHttp({ [DYNASTYPROCESS_IDS_URL]: { status: 503 } }).http)).rejects.toMatchObject({ code: "SOURCE_DOWN", detail: { status: 503 } });
  });

  it("rejects (and never caches) a file below the row floor or without the needed columns", async () => {
    const small = fixtureDynastyCsv();
    expect(fixtureDynastyRows().length).toBeLessThan(DYNASTYPROCESS_MIN_ROWS);
    const { http, calls } = fakeHttp({ [DYNASTYPROCESS_IDS_URL]: { text: small } });
    await expect(fetchDynastyProcessIds(http)).rejects.toMatchObject({ code: "BAD_RESPONSE", detail: { path: "(root)" }, message: expect.stringContaining(`expected at least ${DYNASTYPROCESS_MIN_ROWS.toLocaleString("en-US")}`) });
    const cacheIf = calls[0]?.opts?.cacheIf;
    const res = (text: string) => ({ status: 200, ok: true, isHtml: false, json: undefined, text, fromCache: false });
    expect(cacheIf?.(res(small))).toBe(false);
    expect(cacheIf?.(res(padDynastyCsv(small)))).toBe(true);
    expect(cacheIf?.(res(padDynastyCsv(`${HEADER.replace("espn_id,", "")}\n`)))).toBe(false); // no espn_id column
    expect(DYNASTYPROCESS_MIN_ROWS).toBe(10_000);
  });

  it("reports a saved copy that stood in for a failed refresh", async () => {
    const at = Date.UTC(2026, 8, 27, 14, 0);
    const { http } = fakeHttp({ [DYNASTYPROCESS_IDS_URL]: { text: padDynastyCsv(fixtureDynastyCsv()), stale: true, fetchedAt: at } });
    await expect(fetchDynastyProcessIds(http)).resolves.toMatchObject({ fromCache: true, stale: true, fetchedAt: at });
  });
});
