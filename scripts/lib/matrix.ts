/**
 * Builds the platform × checklist matrix in reports/data-access.md from reports/probe-output/*.json.
 * Only the block between the MATRIX markers is regenerated; hand-written notes elsewhere are kept.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { writeFileAtomic } from "./cache";
import { ROOT } from "./env";
import { ICON, ITEMS, type Check, type Status } from "./checklist";

const OUT_DIR = path.join(ROOT, "reports", "probe-output");
const DATA_ACCESS = path.join(ROOT, "reports", "data-access.md");
const START = "<!-- BEGIN:matrix (generated by npm run probe:all; edit outside this block) -->";
const END = "<!-- END:matrix -->";

/** Summaries of n/a checks that mean "couldn't test yet" rather than "doesn't exist on this platform". */
const UNTESTED = /awaiting|skipped|not tested|untested|no public league/i;

const PLATFORM_COLUMNS = [
  ["espn", "ESPN"],
  ["sleeper", "Sleeper"],
  ["fleaflicker", "Fleaflicker"],
  ["mfl", "MFL"],
  ["yahoo", "Yahoo"],
  ["fantrax", "Fantrax"],
] as const;

interface ProbeOutput {
  platform: string;
  generatedAt: string;
  itemStatus: Record<string, Status>;
  counts: Record<Status, number>;
  checks: Check[];
  runtimeSeconds?: number;
}

export function loadOutputs(): Map<string, ProbeOutput> {
  const out = new Map<string, ProbeOutput>();
  if (!existsSync(OUT_DIR)) return out;
  for (const f of readdirSync(OUT_DIR).filter((x) => x.endsWith(".json"))) {
    try {
      const data = JSON.parse(readFileSync(path.join(OUT_DIR, f), "utf8")) as ProbeOutput;
      out.set(f.replace(/\.json$/, ""), data);
    } catch {
      // ignore unreadable output
    }
  }
  return out;
}

export function renderMatrix(outputs: Map<string, ProbeOutput>): string {
  const lines: string[] = [];
  lines.push("| Item | " + PLATFORM_COLUMNS.map(([, label]) => label).join(" | ") + " |");
  lines.push("|---|" + PLATFORM_COLUMNS.map(() => "---").join("|") + "|");
  for (const [id, title] of Object.entries(ITEMS)) {
    const cells = PLATFORM_COLUMNS.map(([key]) => {
      const o = outputs.get(key);
      if (!o) return "not run";
      const s = o.itemStatus[id];
      if (!s) return "—";
      const subs = o.checks.filter((c) => c.item === id);
      // n/a because nothing could be tested yet (no credentials / no league) is not "not applicable".
      if (s === "na" && subs.some((c) => UNTESTED.test(c.summary))) return "⏸ untested";
      const bad = subs.filter((c) => c.status === "warn" || c.status === "fail").length;
      return `${ICON[s]}${bad ? ` (${bad} of ${subs.length})` : ""}`;
    });
    lines.push(`| ${id}. ${title} | ${cells.join(" | ")} |`);
  }
  lines.push("");
  lines.push(
    "Cells show the worst sub-check; \"(x of y)\" counts sub-checks that are ⚠️ or ❌. ➖ = not applicable on that platform; ⏸ = not tested yet (no credentials or no league; the reason is in the probe output). Details per platform: `reports/probe-output/<platform>.md`.",
  );

  // Checks outside A-M (auth, ID tables, API conventions, docs facts, Sleeper code meanings…).
  const itemIds = new Set(Object.keys(ITEMS));
  const extraRows: string[] = [];
  for (const [key, o] of outputs) {
    if (key.startsWith("shared")) continue;
    const extras = [...new Set(o.checks.filter((c) => !itemIds.has(c.item) && c.item !== "RUN").map((c) => c.item))];
    for (const item of extras) {
      const subs = o.checks.filter((c) => c.item === item);
      const bad = subs.filter((c) => c.status === "warn" || c.status === "fail");
      const status = o.itemStatus[item] ?? "na";
      const icon = status === "na" && subs.some((c) => UNTESTED.test(c.summary)) ? "⏸" : ICON[status];
      extraRows.push(`| ${key} | ${item} | ${icon} ${subs.length} sub-check${subs.length === 1 ? "" : "s"}${bad.length ? ` (${bad.length} ⚠️/❌: ${bad.map((c) => c.key).join(", ")})` : ""} |`);
    }
    const crashed = o.checks.find((c) => c.item === "RUN");
    if (crashed) extraRows.push(`| ${key} | RUN | ${ICON[crashed.status]} ${crashed.summary} |`);
  }
  if (extraRows.length) lines.push("", "**Other platform checks**", "", "| Probe | Check group | Result |", "|---|---|---|", ...extraRows);
  const shared = [...outputs.entries()].filter(([k]) => k.startsWith("shared"));
  for (const [key, o] of shared) {
    lines.push("", `**Shared data sources (${key})**`, "", "| Source | Status | Sub-checks |", "|---|---|---|");
    for (const [item, s] of Object.entries(o.itemStatus)) {
      const subs = o.checks.filter((c) => c.item === item);
      lines.push(`| ${item} | ${ICON[s]} | ${subs.map((c) => `${ICON[c.status]} ${c.title}`).join("<br>")} |`);
    }
  }
  const stamp = [...outputs.values()].map((o) => o.generatedAt).sort().pop();
  lines.push("", `_Generated from probe outputs; latest run ${stamp ?? "n/a"}._`);
  return lines.join("\n");
}

export async function updateDataAccessMatrix(): Promise<void> {
  const block = `${START}\n${renderMatrix(loadOutputs())}\n${END}`;
  let doc = existsSync(DATA_ACCESS) ? readFileSync(DATA_ACCESS, "utf8") : "# Data access — platform × checklist\n\n" + `${START}\n${END}\n`;
  const s = doc.indexOf(START);
  const e = doc.indexOf(END);
  doc = s >= 0 && e > s ? doc.slice(0, s) + block + doc.slice(e + END.length) : doc + "\n" + block + "\n";
  await writeFileAtomic(DATA_ACCESS, doc);
}
