import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT } from "./lib/env";
import { ESPN_API_CONSTANT_PATH, ESPN_API_REPO, parseEspnConstants, type EspnConstants } from "./lib/espn/constants";
import { isMainModule } from "./lib/runMode";

/** The espn-api commit Phase 0 fetched and checked every table against (reports/probe-output/espn.md IDS.commit). */
export const ESPN_API_COMMIT = "663d726c82acdcd1e1f42ecaef35b993ce9ce455";
const OUT_FILE = path.join(ROOT, "src", "adapters", "espn", "constants.ts");

/**
 * EMPIRICAL defaultPositionId table — espn-api has none (its player.py derives the position from
 * eligibleSlots). Phase 0 derived it from ESPN's active player universe (players_wl, 2663 players)
 * plus rosters, cross-checked against Sleeper's and DynastyProcess's espn_id → position
 * (reports/probe-output/espn.md, check E.defaultPosition). src/adapters/espn/constants.test.ts
 * re-verifies it on the committed players_wl fixture. Ids 0, 6 and 8 never occurred.
 */
const EMPIRICAL_DEFAULT_POSITIONS: Record<number, string> = {
  1: "QB",
  2: "RB",
  3: "WR",
  4: "TE",
  5: "K",
  7: "P",
  9: "DT",
  10: "DE",
  11: "LB",
  12: "CB",
  13: "S",
  14: "HC",
  15: "TQB",
  16: "D/ST",
};

const sha256 = (text: string) => createHash("sha256").update(text).digest("hex");

/** Where the Phase 0 probe saved the upstream file (scripts/lib/probe.ts saveRaw → sha256(key) + ".py"). */
function cachedSourcePath(): string {
  return path.join(ROOT, "fixtures", "raw", "espn", `${sha256(`espn-api:${ESPN_API_COMMIT}:${ESPN_API_CONSTANT_PATH}`)}.py`);
}

async function loadSource(): Promise<string> {
  const cached = cachedSourcePath();
  if (existsSync(cached)) return readFileSync(cached, "utf8");
  const url = `https://raw.githubusercontent.com/${ESPN_API_REPO}/${ESPN_API_COMMIT}/${ESPN_API_CONSTANT_PATH}`;
  const res = await fetch(url, { headers: { "User-Agent": "OfferSheet/0.1 (non-commercial; constants generator)" } });
  if (!res.ok) throw new Error(`could not fetch ${ESPN_API_CONSTANT_PATH} at ${ESPN_API_COMMIT.slice(0, 7)} (HTTP ${res.status})`);
  const text = await res.text();
  mkdirSync(path.dirname(cached), { recursive: true });
  writeFileSync(cached, text, "utf8");
  return text;
}

const q = (s: string) => JSON.stringify(s);

function numRecord<T>(name: string, doc: string, rec: Record<number, T>, fmt: (v: T) => string, type: string): string {
  const keys = Object.keys(rec)
    .map(Number)
    .sort((a, b) => a - b);
  const lines = keys.map((k) => `  ${k}: ${fmt(rec[k] as T)},`);
  return `/** ${doc} */\nexport const ${name}: Readonly<Record<number, ${type}>> = {\n${lines.join("\n")}\n};\n`;
}

function strRecord(name: string, doc: string, rec: Record<string, number>): string {
  const keys = Object.keys(rec).sort((a, b) => (rec[a] as number) - (rec[b] as number) || a.localeCompare(b));
  const lines = keys.map((k) => `  ${q(k)}: ${rec[k]},`);
  return `/** ${doc} */\nexport const ${name}: Readonly<Record<string, number>> = {\n${lines.join("\n")}\n};\n`;
}

export function render(c: EspnConstants, sourceSha: string): string {
  const errors = Object.keys(c.parseErrors);
  if (errors.length) throw new Error(`constant.py parse errors in: ${errors.join(", ")}`);
  const parts = [
    `/**
 * GENERATED by scripts/gen-espn-constants.ts — do not edit by hand. Regenerate with:
 *   npx tsx scripts/gen-espn-constants.ts
 *
 * ESPN fantasy football ID tables parsed from ${ESPN_API_REPO}@${ESPN_API_COMMIT.slice(0, 7)}
 * (${ESPN_API_CONSTANT_PATH}, sha256 ${sourceSha.slice(0, 16)}…).
 * espn-api is MIT licensed, Copyright (c) 2018 Christian Wendt: https://github.com/${ESPN_API_REPO}
 *
 * Only ESPN_DEFAULT_POSITIONS is not from espn-api: it is EMPIRICAL (see its comment).
 */

export const ESPN_API_SOURCE = {
  repo: ${q(ESPN_API_REPO)},
  commit: ${q(ESPN_API_COMMIT)},
  path: ${q(ESPN_API_CONSTANT_PATH)},
  sha256: ${q(sourceSha)},
  license: "MIT, Copyright (c) 2018 Christian Wendt",
} as const;
`,
    numRecord("ESPN_LINEUP_SLOTS", "POSITION_MAP, numeric keys: lineup SLOT id → label (20 BE = bench, 21 IR, 23 FLEX, 25 Rookie is a flag, not a slot).", c.slotNames, q, "string"),
    strRecord("ESPN_LINEUP_SLOT_IDS", "POSITION_MAP, string keys: espn-api's reverse entries, label → lineup slot id.", c.slotIdsByName),
    numRecord("ESPN_PRO_TEAMS", "PRO_TEAM_MAP: proTeamId → NFL abbreviation in ESPN's convention (0 = \"None\": no team).", c.proTeams, q, "string"),
    numRecord("ESPN_PLAYER_STATS", "PLAYER_STATS_MAP: statId → stat name in player stat breakdowns.", c.playerStats, q, "string"),
    numRecord("ESPN_SCORING_FORMAT", "SETTINGS_SCORING_FORMAT_MAP: statId → what a scoring rule on it means.", c.scoringFormat, (v) => `{ abbr: ${q(v.abbr)}, label: ${q(v.label)} }`, "{ abbr: string; label: string }"),
    numRecord("ESPN_ACTIVITY", "ACTIVITY_MAP: recent-activity messageTypeId → action.", c.activity, q, "string"),
    `/** TRANSACTION_TYPES (sorted): mTransactions2 row types. */\nexport const ESPN_TRANSACTION_TYPES: readonly string[] = [${c.transactionTypes.map(q).join(", ")}];\n`,
    `/**
 * EMPIRICAL — not from espn-api, which has no defaultPositionId table (its player.py derives a
 * player's position from eligibleSlots). Derived in Phase 0 from ESPN's active player universe and
 * rosters, and cross-checked against Sleeper's and DynastyProcess's espn_id → position
 * (reports/probe-output/espn.md, check E.defaultPosition); re-verified by constants.test.ts on the
 * committed players_wl fixture. player.defaultPositionId → ESPN position name. It is also the key
 * space of scoring pointsOverrides and rosterSettings.positionLimits (checks K.overrideKeys,
 * B.positionLimits). Ids not listed (0, 6, 8, 17+) were never observed.
 */
export const ESPN_DEFAULT_POSITIONS: Readonly<Record<number, string>> = {
${Object.keys(EMPIRICAL_DEFAULT_POSITIONS)
  .map(Number)
  .sort((a, b) => a - b)
  .map((k) => `  ${k}: ${q(EMPIRICAL_DEFAULT_POSITIONS[k] as string)},`)
  .join("\n")}
};
`,
  ];
  return parts.join("\n");
}

async function main(): Promise<void> {
  const source = await loadSource();
  const out = render(parseEspnConstants(source), sha256(source));
  if (process.argv.includes("--check")) {
    // Compare ignoring line-ending style (a Windows checkout may have CRLF).
    const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== out) {
      console.error(`${path.relative(ROOT, OUT_FILE)} is out of date: run npx tsx scripts/gen-espn-constants.ts`);
      process.exit(1);
    }
    console.log(`${path.relative(ROOT, OUT_FILE)} is up to date.`);
    return;
  }
  mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, out, "utf8");
  console.log(`wrote ${path.relative(ROOT, OUT_FILE)} (${out.length} bytes)`);
}

// Run only as a script (an exact path: scripts/lib/runMode.ts isMainModule; a scratch file that imports it starts nothing).
if (isMainModule(import.meta.url)) {
  main().catch((err: unknown) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  });
}
