/**
 * Scoring-oracle results per suite and per rule type (CLAUDE.md §5; Checkpoint 1 "the oracle
 * results, per rule type"). Runs every real-data suite on committed fixtures (no network) and
 * writes reports/oracle-results.md.
 *
 *   npm run oracle:report
 *
 * Offline by nature (planner reply to Checkpoint 4c, A5): the process runs with the offline guard on (scripts/lib/runMode.ts),
 * so nothing here can touch the network; --live changes nothing.
 *
 * Rule-type columns count matched player-weeks in which a wrong reading of that type would have
 * changed the points (engine/oracle.ts ruleTypesIn). ✅ = meets §5's target; ⚠️ = below it but at
 * its documented regression pin (the reason is listed); ❌ = below the pin.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { allOracleSuites, ruleTypeEvidence } from "@/adapters/oracleSuites";
import { config } from "@/engine/config";
import { RULE_TYPES, describeMismatch, type RuleType } from "@/engine/oracle";
import { isMainModule, setNetworkMode } from "./lib/runMode";

function main(): void {
  const suites = allOracleSuites();
  const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
  const totals = Object.fromEntries(RULE_TYPES.map((t) => [t, suites.reduce((n, s) => n + s.summary.ruleTypesExercised[t], 0)])) as Record<RuleType, number>;
  const status = (s: (typeof suites)[number]) => (s.summary.rate >= config.scoring.oracleTarget ? "✅" : s.summary.rate >= s.target ? "⚠️" : "❌");
  const evidence = ruleTypeEvidence(suites);

  const lines: string[] = [
    "# Scoring oracle results",
    "",
    `Generated by \`npm run oracle:report\` from committed fixtures (no network). A player-week matches when our points are within ${config.scoring.oracleTolerance} of the platform's; the target is ${pct(config.scoring.oracleTarget)} (CLAUDE.md §5). Rule-type columns count matched player-weeks in which a wrong reading of that type would have changed the points, so a count is real evidence (a type that only ever scored 0, or where two readings agree, isn't counted).`,
    "",
    `| Suite | Compared with | Matched | Rate | ${RULE_TYPES.join(" | ")} |`,
    `|---|---|---|---|${RULE_TYPES.map(() => "---").join("|")}|`,
    ...suites.map((s, i) => `| ${s.name}${s.note || s.pin ? ` (${i + 1})` : ""} | ${s.source} | ${s.summary.within}/${s.summary.total} | ${pct(s.summary.rate)} ${status(s)} | ${RULE_TYPES.map((t) => s.summary.ruleTypesExercised[t]).join(" | ")} |`),
    `| **All suites** | | ${suites.reduce((n, s) => n + s.summary.within, 0)}/${suites.reduce((n, s) => n + s.summary.total, 0)} | | ${RULE_TYPES.map((t) => `**${totals[t]}**`).join(" | ")} |`,
    "",
    ...suites.flatMap((s, i) => [
      ...(s.pin ? [`(${i + 1}) ${s.name}: below §5's target; held to a regression pin of ${s.pin.within}/${s.pin.total} (its measured result): ${s.pin.why}.`] : []),
      ...(s.note ? [`(${i + 1}) ${s.name}: ${s.note}.`] : []),
    ]),
    "",
    "## Evidence per rule type",
    "",
    "| Rule type | Evidence | |",
    "|---|---|---|",
    ...evidence.map((e) => `| ${e.type} | ${e.evidence} | ${e.status} |`),
    "",
    "✅ = verified against platform-scored points. ⚠️ = derived, indirect or missing platform evidence; the engine's semantics for every type are also covered by unit tests (src/engine/scoring.test.ts).",
    "",
    "## Mismatches",
    "",
  ];
  for (const s of suites) {
    if (!s.summary.mismatches.length) continue;
    lines.push(`### ${s.name} (${s.summary.mismatches.length})`, "", "```", ...s.summary.mismatches.map(describeMismatch), "```", "");
  }
  if (suites.every((s) => !s.summary.mismatches.length)) lines.push("None.", "");

  const out = path.join(process.cwd(), "reports", "oracle-results.md");
  writeFileSync(out, lines.join("\n"));
  console.log(lines.slice(0, lines.indexOf("## Mismatches")).join("\n"));
  console.log(`\nwrote ${path.relative(process.cwd(), out)}`);
}

// Run only as a script (an exact path: scripts/lib/runMode.ts isMainModule), with the offline guard on: committed fixtures only.
if (isMainModule(import.meta.url)) {
  setNetworkMode(false);
  main();
}
