/**
 * import:report offline by default (planner reply to Checkpoint 4c, A5): its command line and the Import Report from a
 * saved dump, on Parker's committed sanitized ESPN fixture with synthetic model inputs, written as a dump to a temporary
 * folder. No network, no .env.local.
 */
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { normalizeEspnLeague } from "@/adapters/espn/normalize";
import { NOW, PARKER, fakeResolver, parkerBundle } from "@/adapters/espn/test-helpers";
import { syntheticInputs } from "@/engine/testLeague";
import { IMPORT_FORMAT_VERSION, toStoredImport } from "@/lib/importStore";
import { OFFLINE_OVERRIDES_TEXT, OFFLINE_SLEEPER_TEXT, importReportCommand, offlineReport, parseImportReportArgs } from "./import-report";
import { loadDump } from "./league-report";

const root = mkdtempSync(path.join(tmpdir(), "import-report-"));
afterAll(() => rmSync(root, { recursive: true, force: true }));

// The fixture's snapshot as the import made it, with real-looking names a dump must never show (loadDump puts the
// placeholders on again).
const raw = normalizeEspnLeague(parkerBundle(), { leagueId: PARKER.leagueId, resolver: fakeResolver(), now: NOW, swid: PARKER.swid }).snapshot;
const named = { ...raw, name: "Secret League Name", myTeamId: "3", teams: raw.teams.map((t) => ({ ...t, name: `Secret Team ${t.id}`, ownerName: `Secret Owner ${t.id}` })) };
const dir = path.join(root, "data-local", "parker-league-test");
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "snapshot.json"), JSON.stringify(named));
writeFileSync(path.join(dir, "inputs.json"), JSON.stringify(syntheticInputs(raw)));
writeFileSync(path.join(dir, "meta.json"), JSON.stringify({ now: NOW.toISOString() }));

describe("import:report: the command line (offline by default)", () => {
  const dumps = () => [{ dir, now: NOW }];

  it("reads the newest dump unless --live; --test-leagues needs --live; the header names the dump", () => {
    const offline = parseImportReportArgs([], root, { env: {}, dumps });
    expect(offline).toEqual({ dump: dir, newest: true, team: undefined, cookies: null, testLeagues: false, responseOut: undefined });
    if ("error" in offline) throw new Error(offline.error);
    expect(importReportCommand(offline, root)).toBe("npm run import:report -- --dump data-local/parker-league-test");
    const live = parseImportReportArgs(["--live", "--test-leagues", "--no-cookies"], root, { env: {}, dumps });
    if ("error" in live) throw new Error(live.error);
    expect(live).toMatchObject({ dump: null, testLeagues: true, cookies: "off" });
    expect(importReportCommand(live, root)).toBe("npm run import:report -- --live --no-cookies --test-leagues");
    expect(parseImportReportArgs(["--test-leagues"], root, { env: {}, dumps })).toEqual({ error: expect.stringContaining("needs --live") });
    expect(parseImportReportArgs(["--response-out"], root, { env: {}, dumps })).toEqual({ error: expect.stringContaining("--response-out needs a file") });
    expect(parseImportReportArgs(["--response-out", "x.json"], root, { env: {}, dumps })).toMatchObject({ responseOut: path.join(root, "x.json") });
  });
});

describe("import:report from a saved dump", () => {
  const dump = loadDump(dir);
  const { doc, response } = offlineReport(dump, { root, dir, timeZone: "UTC", command: "npm run import:report -- --dump data-local/parker-league-test", generatedAt: new Date("2026-10-04T12:00:00.000Z") });

  it("says where the data came from and what a dump doesn't keep, and renders the league's Import Report", () => {
    expect(doc).toContain("Generated by `npm run import:report -- --dump data-local/parker-league-test` on 2026-10-04 from a saved dump, with no network");
    expect(doc).toContain(`- Offline: the git-ignored dump in data-local/parker-league-test/ (made by the app's own import and model-inputs builder at ${NOW.toISOString()}`);
    expect(doc).toContain("not the import's own notes");
    expect(doc).toContain("## ESPN: Parker's league (the saved dump, as imported through the public link)");
    expect(doc).toContain("**Scoring: ");
    expect(doc).toContain("- Waiver order used: ");
    expect(doc).toContain(OFFLINE_SLEEPER_TEXT);
    expect(doc).toContain(OFFLINE_OVERRIDES_TEXT);
  });

  it("shows the dump's team as picked (dump-final sets it by hand), and placeholders only", () => {
    expect(doc).toContain("your team: Team 3 (picked)");
    expect(doc).toContain("| Team 3 (you) | Owner 3 |");
    expect(doc).not.toMatch(/Secret/);
    expect(response.snapshot.myTeamId).toBeNull();
    expect(response.snapshot.name).toBe("League 1");
  });

  it("can still save the Import Report page's record (--response-out), in the app's current format", () => {
    const stored = toStoredImport({ request: { platform: "espn", season: response.snapshot.season, leagueId: "{leagueId}" }, response, savedAt: "2026-10-04T12:00:00.000Z" });
    expect(stored.version).toBe(IMPORT_FORMAT_VERSION);
    expect(JSON.stringify(stored)).not.toMatch(/Secret/);
  });
});
